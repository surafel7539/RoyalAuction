export function translate(locale, key, vars) {
  const table = locale === "am" ? am : en;
  const template = table[key] || en[key] || key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? "" : String(vars[name])));
}

export function categoryName(locale, category) {
  const slug = typeof category === "string" ? category : category?.slug;
  const fallback = typeof category === "string" ? category : category?.name || "";
  return categories[locale]?.[slug] || categories.en[slug] || fallback;
}

